#!/bin/bash
# dod.sh: the Definition of Done (PLAN 3). Safe in N worktrees at once; fails fast; one line per step.
#   ios/scripts/dod.sh [--ticket Tn|T0|A<n>|P<n>] [--merge] [--checks-only] [--no-ui] [--no-sim] [--record] [--keep-sim] [--cleanup] [--self-test]
# Ends with `DOD PASS <ticket|merge> <sha>`, `DOD FAIL <step>`, `DOD PARTIAL` (--no-sim), `DOD CHECKS PASS`, or `DOD RECORDED` (--record).
# Environment: STMP_ANDROID_REPO, STMP_BASELINE_SHA (required), STMP_BASE, STMP_MIN_FREE_GB (12), STMP_HOST_SLOTS (2),
#   STMP_DOD_SLOTS (2), STMP_STEP_TIMEOUT_MIN (40), STMP_SEED_DIRS, STMP_RUN_STATE, STMP_ALLOW_MAIN_COMMON_DIR (see context step).
# Safety rules (hard-coded): CODE_SIGNING_ALLOWED=NO always; never archive/-exportArchive/altool/notarytool; never touches the main
# checkout; never pushes.
set -uo pipefail
HERE=$(cd "$(dirname "$0")" && pwd); IOS=$(cd "$HERE/.." && pwd)
MAIN_CHECKOUT=/Users/mohamed/Developer/STMP.AI
TICKET=""; MERGE=0; CHECKS_ONLY=0; NO_UI=0; NO_SIM=0; RECORD=0; KEEP_SIM=0; CLEANUP=0; SELF=0
while [ $# -gt 0 ]; do case "$1" in
  --ticket) TICKET="${2:-}"; shift 2;; --merge) MERGE=1; shift;; --checks-only) CHECKS_ONLY=1; shift;; --no-ui) NO_UI=1; shift;;
  --no-sim) NO_SIM=1; shift;; --record) RECORD=1; shift;; --keep-sim) KEEP_SIM=1; shift;; --cleanup) CLEANUP=1; shift;;
  --self-test) SELF=1; shift;; *) echo "dod: unknown argument $1" >&2; exit 2;; esac; done

say() { echo "DOD $*"; }
LOG_TAIL=""
die() { say "FAIL $1${2:+ ($2)}"; if [ -n "$LOG_TAIL" ] && [ -f "$LOG_TAIL" ]; then tail -40 "$LOG_TAIL" | sed 's/^/    /'; fi; exit 1; }
SLOT_HELD=""; SLOT_KIND=""; SLOT_TOTAL=1; UDID=""; MERGE_LOCK=""

# ---------------- attribution (D64) ----------------
ATTR_PATTERNS=('co-authored-by:' 'generated (with|by)' '(^|[^./[:alnum:]_])claude([^[:alnum:]_]|$)' 'anthropic' '🤖' 'noreply@anthropic' '(assisted|written|created) by (an )?ai([^[:alnum:]_]|$)')
attribution_hit() { local l="$1" p; for p in "${ATTR_PATTERNS[@]}"; do printf '%s\n' "$l" | grep -Eiq -- "$p" && return 0; done; return 1; }
self_test() {
  local fail=0 l
  for l in "feat: AISummarizer no-op" "docs: AI summaries are not in v1" "docs: link .claude/handover notes" "fix: the Claudius bug"; do
    attribution_hit "$l" && { echo "SELF-TEST FAIL (pass list hit): $l"; fail=1; }; done
  for l in "Co-Authored-By: Someone <a@example.com>" "Generated with a tool" "generated by a tool" "made with Claude Code" "Anthropic" "🤖 robot" "noreply@anthropic.com" "written by AI" "created by an ai"; do
    attribution_hit "$l" || { echo "SELF-TEST FAIL (fail list missed): $l"; fail=1; }; done
  "$HERE/ownership-check.sh" --self-test || fail=1
  # the step watchdog kills a runaway command and reports the timeout
  OUT=$(mktemp -d); STMP_STEP_TIMEOUT_SEC=1 STMP_RETRY=0 run_capped selftest sleep 30 && { echo "SELF-TEST FAIL: watchdog did not fire"; fail=1; }
  [ "$CAPPED_TIMED_OUT" = 1 ] || { echo "SELF-TEST FAIL: timeout not flagged"; fail=1; }
  rm -rf "$OUT"
  if [ $fail = 0 ]; then echo "dod self-test: ok"; exit 0; fi
  exit 1
}

# ---------------- timeouts (D72) ----------------
killtree() { local c; for c in $(pgrep -P "$1" 2>/dev/null); do killtree "$c" "$2"; done; kill "-$2" "$1" 2>/dev/null || true; }
slots_busy() { local base="$1" n=0 d; for d in "$base"/*; do if [ -f "$d/pid" ] && kill -0 "$(cat "$d/pid" 2>/dev/null)" 2>/dev/null; then n=$((n+1)); fi; done; echo $n; }
CAPPED_TIMED_OUT=0
run_capped() { # step cmd... ; log in $OUT/logs/<step>.log ; one automatic retry on timeout
  local step="$1"; shift; local cap=${STMP_STEP_TIMEOUT_SEC:-$(( ${STMP_STEP_TIMEOUT_MIN:-40} * 60 ))} attempt=0 rc pid wd
  mkdir -p "$OUT/logs"; LOG_TAIL="$OUT/logs/$step.log"
  while :; do
    attempt=$((attempt+1)); CAPPED_TIMED_OUT=0
    "$@" >"$LOG_TAIL" 2>&1 & pid=$!
    ( sleep "$cap"; echo timeout > "$OUT/logs/$step.timeout"; killtree $pid TERM; sleep 5; killtree $pid KILL ) & wd=$!
    wait $pid; rc=$?
    kill $wd 2>/dev/null; wait $wd 2>/dev/null
    if [ -f "$OUT/logs/$step.timeout" ]; then
      rm -f "$OUT/logs/$step.timeout"; CAPPED_TIMED_OUT=1
      [ -n "$UDID" ] && "$HERE/sim.sh" shutdown "$UDID"
      if [ $attempt -lt 2 ] && [ "${STMP_RETRY:-1}" = 1 ]; then say "RETRY timeout $step"; continue; fi
      return 124
    fi
    return $rc
  done
}
run_step() { # step cmd... : failure -> DOD FAIL (timeout and network named)
  local step="$1"; shift; run_capped "$step" "$@"; local rc=$?
  if [ $rc = 124 ]; then
    local busy; busy=$(slots_busy "/tmp/stmp-${SLOT_KIND:-host}-slots"); say "FAIL timeout $step slots=$busy/$SLOT_TOTAL"; exit 1
  fi
  if [ $rc != 0 ]; then
    if grep -Eqi 'could not resolve host|network is unreachable|failed to clone|Could not resolve package|unable to access|Failed to fetch|connection (refused|reset|timed out)|The Internet connection appears to be offline' "$LOG_TAIL"; then
      say "FAIL network $step (not charged, D143)"; tail -15 "$LOG_TAIL" | sed 's/^/    /'; exit 1; fi
    die "$step"
  fi
}

# ---------------- slots ----------------
acquire_slot() { # kind lo hi -> sets SLOT_HELD
  local kind="$1" lo="$2" hi="$3" base="/tmp/stmp-$1-slots" waited=0 n d
  mkdir -p "$base"; SLOT_TOTAL=$((hi-lo+1)); SLOT_KIND="$kind"
  while :; do
    for n in $(seq "$lo" "$hi"); do d="$base/$n"
      if mkdir "$d" 2>/dev/null; then echo $$ > "$d/pid"; SLOT_HELD="$d"; return 0; fi
      if [ -f "$d/pid" ] && ! kill -0 "$(cat "$d/pid" 2>/dev/null)" 2>/dev/null; then
        rm -rf "$d"; if mkdir "$d" 2>/dev/null; then echo $$ > "$d/pid"; SLOT_HELD="$d"; return 0; fi; fi
    done
    [ $waited -ge 1800 ] && die "slot" "no $kind slot in 30 min"
    sleep 5; waited=$((waited+5)); [ $((waited % 300)) = 0 ] && say "WAIT slot ($kind, $((waited/60)) min)"
  done
}
release_slot() { if [ -n "$SLOT_HELD" ]; then rm -rf "$SLOT_HELD"; fi; SLOT_HELD=""; }
cleanup_exit() { if [ -n "$UDID" ] && [ $KEEP_SIM = 0 ]; then "$HERE/sim.sh" shutdown "$UDID"; fi; release_slot; if [ -n "$MERGE_LOCK" ]; then rm -rf "$MERGE_LOCK"; fi; }
trap cleanup_exit EXIT
trap 'exit 130' INT TERM

xb() { # xcodebuild wrapper: safety rules
  local a; for a in "$@"; do case "$a" in archive|-exportArchive|altool|notarytool) echo "dod: refusing xcodebuild $a" >&2; return 99;; esac; done
  xcodebuild "$@" CODE_SIGNING_ALLOWED=NO
}

[ $SELF = 1 ] && self_test
if [ $MERGE = 0 ] && [ $CLEANUP = 0 ] && [ -z "$TICKET" ]; then echo "usage: dod.sh --ticket Tn|--merge|--self-test|--cleanup" >&2; exit 2; fi
[ -z "$TICKET" ] || [[ "$TICKET" =~ ^(T[0-9]+|A[0-9]+|P[0-9]+)$ ]] || die "ticket" "bad id $TICKET"

# ---------------- 1. context ----------------
ROOT=$(/usr/bin/git rev-parse --show-toplevel 2>/dev/null) || die context "not a git checkout"
[ "$ROOT" = "$MAIN_CHECKOUT" ] && die context "refusing to run in the main checkout"
COMMON=$(/usr/bin/git rev-parse --path-format=absolute --git-common-dir)
case "$COMMON/" in "$MAIN_CHECKOUT"/*) [ "${STMP_ALLOW_MAIN_COMMON_DIR:-0}" = 1 ] || die context "git common dir is inside the main checkout (D40); use the iOS clone, or STMP_ALLOW_MAIN_COMMON_DIR=1 for a worktree of it";; esac
SLUG="$(basename "$ROOT" | tr -c 'A-Za-z0-9\n' '-')-$(printf '%s' "$ROOT" | shasum | cut -c1-6)"
OUT="$ROOT/ios/.derived"; DD="$OUT/DerivedData"; SPM="$OUT/spm-host"; PKGS="$OUT/SourcePackages"; mkdir -p "$OUT"
BASE=$(/usr/bin/git merge-base HEAD "${STMP_BASE:-ios/native-client}" 2>/dev/null) || die context "no merge-base with ${STMP_BASE:-ios/native-client}"
. "$HERE/sim.env"
if [ $CLEANUP = 1 ]; then
  "$HERE/sim.sh" delete "STMP-$SLUG"; rm -rf "$OUT"; say "CLEANED $SLUG"; exit 0
fi
echo "xcodegen $(/opt/homebrew/bin/xcodegen --version 2>&1 | head -1) | $(xcodebuild -version 2>&1 | head -1) | $(swift --version 2>&1 | grep -o 'Swift version [0-9.]*')"
swift --version 2>&1 | grep -q 'Swift version 6\.' || die context "Swift 6.x required"
FREE=$(df -g "$ROOT" | awk 'NR==2{print $4}'); [ "${FREE:-0}" -ge "${STMP_MIN_FREE_GB:-12}" ] || die disk "${FREE:-?} GiB free, need ${STMP_MIN_FREE_GB:-12}"
if [ $NO_SIM = 0 ] && [ $CHECKS_ONLY = 0 ]; then xcrun simctl list runtimes | grep -q "$STMP_SIM_RUNTIME" || die runtime "$STMP_SIM_RUNTIME is not installed"; fi
export STMP_ANDROID_REPO="${STMP_ANDROID_REPO:-/Users/mohamed/Developer/STMP.AI-integration}"
if [ -z "${STMP_BASELINE_SHA:-}" ] || ! /usr/bin/git -C "$STMP_ANDROID_REPO" cat-file -e "$STMP_BASELINE_SHA" 2>/dev/null; then die baseline "STMP_BASELINE_SHA unset or not in $STMP_ANDROID_REPO"; fi
say "step 1 context ok (slug $SLUG)"

# ---------------- 2. hygiene ----------------
cd "$ROOT"
BAD=$(/usr/bin/git ls-files ios | grep -E '(^|/)Secrets\.xcconfig$|\.pbxproj$|\.xcodeproj/|(^|/)local\.properties$|\.jks$|\.keystore$|\.p12$|\.mobileprovision$' || true)
[ -z "$BAD" ] || die hygiene "tracked secrets or generated files: $BAD"
while IFS= read -r l; do if attribution_hit "$l"; then die hygiene "attribution in a commit message: $l"; fi; done < <(/usr/bin/git log --format=%B "$BASE..HEAD")
BADSUBJ=$(/usr/bin/git log --format=%s "$BASE..HEAD" | grep -Ev '^((feat|fix|refactor|docs|test|chore|perf|ci): |fixup! )' || true); [ -z "$BADSUBJ" ] || die hygiene "commit subject: $BADSUBJ"
EMAILS=$(grep -rEho '[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+\.[A-Za-z]{2,}' ios/contract 2>/dev/null | grep -Eiv '@example\.com$' || true); [ -z "$EMAILS" ] || die hygiene "non-example.com address in ios/contract: $EMAILS"
if grep -rEl '^[[:space:]]*import Testing' ios/STMPKit ios/App --include='*.swift' 2>/dev/null | grep -q .; then die hygiene "import Testing (D60)"; fi
if grep -rEl '^[[:space:]]*import XCTest' ios/STMPKit/Sources/STMPTestSupport 2>/dev/null | grep -q .; then die hygiene "import XCTest under STMPTestSupport (D111)"; fi
UNSAFE=$(grep -rnE '@unchecked +Sendable' ios/STMPKit/Sources ios/App/Sources --include='*.swift' 2>/dev/null | while IFS=: read -r f n rest; do
  prev=$(sed -n "$((n>1?n-1:1)),${n}p" "$f"); echo "$prev" | grep -q 'SAFETY:' || echo "$f:$n"; done)
[ -z "$UNSAFE" ] || die hygiene "@unchecked Sendable without // SAFETY: $UNSAFE"
PR=$(grep -rnE '(^|[^A-Za-z_.])print\(' ios/STMPKit/Sources ios/App/Sources --include='*.swift' 2>/dev/null | grep -Ev '^[^:]*:[0-9]+:[[:space:]]*//' || true); [ -z "$PR" ] || die hygiene "print( in Sources: $PR"
TESTDIRS="ios/STMPKit/Tests ios/App/Tests ios/App/UITests"
SLEEP=$(grep -rnE 'Task\.sleep|Thread\.sleep|usleep\(|(^|[^A-Za-z_.])sleep\(' $TESTDIRS --include='*.swift' 2>/dev/null || true); [ -z "$SLEEP" ] || die hygiene "sleep in tests (D45): $SLEEP"
LONGWAIT=$(grep -rnE 'timeout: *([3-9][1-9]|[4-9][0-9]|[0-9]{3,})' $TESTDIRS --include='*.swift' 2>/dev/null || true); [ -z "$LONGWAIT" ] || die hygiene "expectation timeout over 30 s: $LONGWAIT"
SNAP=$(grep -rnE '(^|[^A-Za-z_])assertSnapshot\(' ios/App/Tests ios/STMPKit/Tests --include='*.swift' 2>/dev/null | grep -v 'ios/App/Tests/Support/' || true); [ -z "$SNAP" ] || die hygiene "assertSnapshot( outside the helper: $SNAP"
XCF=$(grep -rnE 'XCTExpectFailure' $TESTDIRS --include='*.swift' 2>/dev/null | grep -Ev 'BLOCKED P[0-9]+' || true); [ -z "$XCF" ] || die hygiene "XCTExpectFailure without BLOCKED P<n>: $XCF"
VT=$(grep -rnE '(^|[^A-Za-z_])Date\(\)|Date\.now|style: *\.(relative|timer)' ios/App/Sources/Features ios/App/Sources/DesignSystem --include='*.swift' 2>/dev/null || true); [ -z "$VT" ] || die hygiene "wall-clock time in views (D70): $VT"
isolation_violations() { # D54: a Platform type conforming to a seam must be nonisolated or an actor
  local seam
  while read -r seam; do
    if [ -z "$seam" ] || [ "${seam#\#}" != "$seam" ]; then continue; fi
    grep -rnE "^[^/]*(class|struct|enum|actor) +[A-Za-z0-9_]+ *:[^{]*\b$seam\b" ios/App/Sources/Platform --include='*.swift' 2>/dev/null | grep -Ev 'nonisolated|actor +[A-Za-z0-9_]+ *:' || true
  done < "$HERE/seams.txt"
}
ISO=$(isolation_violations); [ -z "$ISO" ] || die hygiene "Platform adapter must be nonisolated or an actor (D54): $ISO"
"$HERE/symbols-check.sh" || die symbols
"$HERE/source-check.sh" || die source-check
"$HERE/contract-drift.sh" | grep -E 'DRIFT' | sed 's/^/    warn: /' || true
"$HERE/resolved-check.sh" || die resolved-check
say "step 2 hygiene ok"

# ---------------- 3. ownership ----------------
if [ -n "$TICKET" ]; then "$HERE/ownership-check.sh" --ticket "$TICKET" || die ownership; say "step 3 ownership ok"; fi
# ---------------- 4. changelog ----------------
if [ $MERGE = 1 ]; then "$HERE/changelog-check.sh" --merge || die changelog; else "$HERE/changelog-check.sh" --ticket "$TICKET" || die changelog; fi
say "step 4 changelog ok"
if [ $CHECKS_ONLY = 1 ]; then say "CHECKS PASS"; exit 0; fi

# ---------------- 5. lint ----------------
xcrun swift-format lint --strict --recursive --configuration "$IOS/.swift-format" ios/STMPKit ios/App >"$OUT/lint.log" 2>&1 || { LOG_TAIL="$OUT/lint.log"; die lint; }
say "step 5 lint ok"

# ---------------- seeding (D143) ----------------
seed() { local name="$1" dest="$2" cand
  [ -d "$dest" ] && return 0
  for cand in ${STMP_SEED_DIRS:-/Users/mohamed/Developer/STMP.AI-ios/repo/ios/.derived /Users/mohamed/Developer/STMP.AI-ios/ios/.derived}; do
    if [ -d "$cand/$name" ] && [ "$cand" != "$OUT" ]; then cp -cR "$cand/$name" "$dest" 2>/dev/null && return 0; fi; done
  return 0; }
seed spm-host "$SPM"; seed SourcePackages "$PKGS"

# ---------------- 6. package on the host ----------------
acquire_slot host 1 "${STMP_HOST_SLOTS:-2}"
run_step swift-test swift test --package-path ios/STMPKit --scratch-path "$SPM" --parallel --force-resolved-versions --disable-automatic-resolution
release_slot
say "step 6 package tests ok ($(grep -Eo 'Executed [0-9]+ tests' "$OUT/logs/swift-test.log" | tail -1))"
if [ $NO_SIM = 1 ]; then say "PARTIAL (no simulator, inner loop only)"; exit 0; fi

# ---------------- 7. generate ----------------
/opt/homebrew/bin/xcodegen generate --spec ios/project.yml --quiet || die xcodegen
mkdir -p ios/STMP.xcodeproj/project.xcworkspace/xcshareddata/swiftpm && cp ios/Package.resolved ios/STMP.xcodeproj/project.xcworkspace/xcshareddata/swiftpm/Package.resolved
say "step 7 xcodegen ok"

# ---------------- 8/9. simulator slot ----------------
if [ $MERGE = 1 ]; then
  if [ "${STMP_MERGE_LOCK_HELD:-0}" != 1 ]; then
    while ! mkdir /tmp/stmp-merge.lock 2>/dev/null; do
      p=$(cat /tmp/stmp-merge.lock/pid 2>/dev/null || echo 0)
      if ! kill -0 "$p" 2>/dev/null; then rm -rf /tmp/stmp-merge.lock; continue; fi
      sleep 5; done
    echo $$ > /tmp/stmp-merge.lock/pid; MERGE_LOCK=/tmp/stmp-merge.lock
  fi
  acquire_slot dod 0 0
else acquire_slot dod 1 "${STMP_DOD_SLOTS:-2}"; fi
UDID=$("$HERE/sim.sh" ensure "STMP-$SLUG") || die simulator
say "step 9 simulator $UDID"

# ---------------- 10. app tests ----------------
RECMODE=never; [ $RECORD = 1 ] && RECMODE=missing
XBFLAGS=(-project ios/STMP.xcodeproj -scheme STMP -destination "platform=iOS Simulator,id=$UDID" -derivedDataPath "$DD" -clonedSourcePackagesDirPath "$PKGS" -onlyUsePackageVersionsFromResolvedFile -disableAutomaticPackageResolution)
run_step build-for-testing xb build-for-testing "${XBFLAGS[@]}"
STAMP=$(date +%Y%m%d-%H%M%S); RES="$OUT/results/$STAMP.xcresult"; mkdir -p "$OUT/results"
SKIP=(); [ $NO_UI = 1 ] && SKIP=(-skip-testing:STMPUITests)
export TEST_RUNNER_SNAPSHOT_TESTING_RECORD="$RECMODE"
run_step test-without-building xb test-without-building "${XBFLAGS[@]}" -parallel-testing-enabled NO -resultBundlePath "$RES" ${SKIP[@]+"${SKIP[@]}"}
say "step 10 app tests ok ($(grep -Eo 'Executed [0-9]+ tests' "$OUT/logs/test-without-building.log" | tail -1))"
if [ $RECORD = 1 ]; then say "RECORDED (not a DoD result; run plain dod.sh --ticket $TICKET next)"; exit 0; fi

# ---------------- merge extras ----------------
if [ $MERGE = 1 ]; then
  run_step release-build xb build -project ios/STMP.xcodeproj -scheme STMP -configuration Release -destination generic/platform=iOS -derivedDataPath "$DD-release" -clonedSourcePackagesDirPath "$PKGS" -onlyUsePackageVersionsFromResolvedFile -disableAutomaticPackageResolution
  BIN="$DD-release/Build/Products/Release-iphoneos/STMP.app/STMP"; [ -f "$BIN" ] || die release-binary "missing $BIN"
  for opt in -STMPTestBind -STMPResetState -STMPStorageRoot -STMPSkipOnboarding -STMPSeedPolicy STMP_TEST_PORT; do
    if strings -a "$BIN" | grep -qF -- "$opt"; then die release-strings "Release binary contains $opt (D56)"; fi; done
  if nm "$BIN" 2>/dev/null | grep -q 'STMPTestSupport'; then die release-nm "Release binary links STMPTestSupport symbols (D111)"; fi
  say "merge extras ok (Release device build, strings, nm)"
fi
SHA=$(/usr/bin/git rev-parse --short HEAD)
say "PASS ${TICKET:-merge} $SHA"
